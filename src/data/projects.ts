import type { ImageMetadata } from 'astro';
import type { Item, LoopMedia, Project, StackMedia, StillMedia } from './types';

/* Imágenes procesadas por tools/media.py (src/assets/work). Los textos son
   cortos a propósito: cada proyecto es una muestra. Los que son sitios van
   directo al sitio; el resto abre una ventana con su galería, y la burbuja
   que acompaña al cursor cuenta lo justo (says). */
const files = import.meta.glob<{ default: ImageMetadata }>('../assets/work/**/*.{jpg,png}', { eager: true });
const img = (p: string) => {
  const m = files[`../assets/work/${p}`];
  if (!m) throw new Error(`falta la imagen ${p}`);
  return m.default;
};
const still = (p: string, alt: string, span?: number): StillMedia & Item => ({ kind: 'image', img: img(p), alt, span });
/** una lámina que ya dice lo suyo: sin burbuja al pasar */
const quiet = (p: string, alt: string, span?: number): StillMedia & Item => ({ ...still(p, alt, span), say: false });
const loop = (p: string, label: string, ratio = '16 / 9', span?: number): LoopMedia & Item => ({
  kind: 'loop',
  src: `/media/${p}`,
  poster: `/media/${p}.jpg`,
  ratio,
  label,
  span,
});

